export function filterStates({ rooms = null, ids = null } = {}) {
  let list = STATES
  if (rooms?.length) {
    const allowed = new Set(rooms.map((r) => r.toLowerCase()))
    list = list.filter((s) => allowed.has(s.room.toLowerCase()))
  }
  if (ids?.length) {
    const allowed = new Set(ids.map((id) => id.toLowerCase()))
    list = list.filter((s) => allowed.has(s.id.toLowerCase()))
  }
  return list
}
