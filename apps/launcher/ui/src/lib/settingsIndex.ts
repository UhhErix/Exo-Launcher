export function searchSettings(query: string): SettingsIndexEntry[] {
  const tokens = query.trim().toLowerCase().split(/\s+/).filter(Boolean)
  if (tokens.length === 0) return []
  const matches = SETTINGS_INDEX.filter((entry) => {
    const haystack = `${entry.label} ${entry.pageLabel} ${entry.keywords.join(' ')}`.toLowerCase()
    return tokens.every(token => haystack.includes(token))
  })
  return [...matches].sort((a, b) => {
    const q = tokens.join(' ')
    const al = a.label.toLowerCase()
    const bl = b.label.toLowerCase()
    const aStarts = al.startsWith(q) ? 0 : al.includes(q) ? 1 : 2
    const bStarts = bl.startsWith(q) ? 0 : bl.includes(q) ? 1 : 2
    return aStarts - bStarts
  })
}
