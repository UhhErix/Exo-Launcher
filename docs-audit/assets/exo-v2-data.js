window.mountWootingMatrix = function(container, opts = {}) {
  const activeKey = opts.selected || "W";
  const actuation = opts.actuation || "0.4";
  const rt = opts.rt || "0.15";
  const html = WOOTING_SPLIT_ROWS.map(row => {
    const keys = row.map(k => {
      const cls = [
        "wk-key",
        k.kind ? `is-${k.kind}` : "",
        k.id === activeKey ? "is-selected" : ""
      ].filter(Boolean).join(" ");
      const badge = (k.kind === "wasd" || k.kind === "space")
        ? `<span class="wk-act tabular">${actuation}</span>`
        : (k.sub ? `<span class="wk-sub tabular">${k.sub}</span>` : "");
      const subBar = k.kind === "space"
        ? `<span class="wk-space-bar"></span>`
        : "";
      return `<button type="button" class="${cls}" style="flex:${k.u} 0 0" data-key="${k.id}">
        <span class="wk-lbl">${k.label}</span>
        ${subBar}
        ${badge}
      </button>`;
    }).join("");
    return `<div class="wk-row">${keys}</div>`;
  }).join("");
  container.innerHTML = `<div class="wk-chassis">${html}</div>`;
  container.querySelectorAll(".wk-key").forEach(btn => {
    btn.addEventListener("click", () => {
      container.querySelectorAll(".wk-key.is-selected").forEach(x => x.classList.remove("is-selected"));
      btn.classList.add("is-selected");
      if (opts.onSelect) opts.onSelect(btn.dataset.key, btn.querySelector(".wk-lbl").textContent);
    });
  });
};
