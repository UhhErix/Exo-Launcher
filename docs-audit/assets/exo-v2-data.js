window.renderTopStageTrack = function(activeIdx, options = {}) {
  const defaultStages = [
    { label: "Welcome", sub: "Instant local scan" },
    { label: "Accounts & stores", sub: "4 stores · 215 games" },
    { label: "Devices", sub: "4 devices" },
    { label: "PC defaults", sub: "RTX 3070 · Ryzen 5600X" },
    { label: "Live tour", sub: "3 hands-on actions" }
  ];
  const stages = defaultStages.map((s, i) => ({
    label: (options.labels && options.labels[i]) || s.label,
    sub: (options.subs && options.subs[i]) || s.sub
  }));
  const nodes = stages.map((s, i) => {
    const customState = options.states && options.states[i];
    const state = customState || (i < activeIdx ? "done" : (i === activeIdx ? "current" : "upcoming"));
    const cls = state === "done" ? "is-done" : (state === "current" ? "is-active" : (state === "skipped" ? "is-skipped" : ""));
    const num = state === "done" ? EXO_ICONS.check : (state === "skipped" ? "–" : (i + 1));
    const statePill = state === "done"
      ? `<span class="stage-state is-done">Done</span>`
      : state === "current"
        ? `<span class="stage-state is-active">Current</span>`
        : state === "skipped"
          ? `<span class="stage-state is-skipped">Skipped</span>`
          : "";
    return `<div class="stage-node ${cls}">
      <span class="stage-num">${num}</span>
      <div class="stage-copy">
        <div class="stage-head">
          <span class="stage-label">${s.label}</span>
          ${statePill}
        </div>
        <div class="stage-sub tabular">${s.sub}</div>
      </div>
    </div>`;
  }).join("");
  const rightAction = options.hideSkip
    ? `<button class="exo-btn is-sm is-ghost" onclick="document.body.classList.toggle('reduce-motion')">Reduce motion</button>`
    : `<button class="exo-btn is-sm is-ghost" onclick="document.body.classList.toggle('reduce-motion')">Reduce motion</button>
       <button class="exo-btn is-sm">Skip setup</button>`;
  return `<header class="setup-topbar">
    <div class="setup-brand">${renderExoMark(24)}<span>Exo</span><span class="sub">Setup</span></div>
    <nav class="stage-track" aria-label="Setup stages">${nodes}</nav>
    <div class="setup-topbar-actions">${rightAction}</div>
  </header>`;
};

